"""The shared state and cross-mixin operations of :class:`BrakeEngine`.

The engine is split across four mixins that share nothing but ``self``. Annotating that ``self``
with ``BrakeEngine`` would be circular, so it is declared here as a protocol: the mixins see the
contract they actually use, and mypy checks every access against it instead of needing a
``# type: ignore[misc]`` on every method. ``BrakeEngine`` provides the implementation; nothing here
runs.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from ..config import Settings
    from ..models import (
        CueKind,
        DropReason,
        Sample,
        SectorOutcome,
        SectorResult,
        SectorRun,
        SectorStatus,
        TrackData,
    )
    from ..timeline import CarAt, PositionTimeline
    from .cues import _BrakeEvent
    from .passes import _LapRun, _LostPass, _Pass


class EngineState(Protocol):
    """Everything the four engine mixins read or call on ``self``.

    Kept next to the engine rather than in the mixins so neither mixin needs to import another for
    type checking. Attribute types are the full types the state can hold between samples.
    """

    # ------------------------------------------------------------------ callbacks
    _on_cue: Callable[[CueKind], None]
    _on_sector: Callable[[SectorResult], None]
    _on_message: Callable[[str], None]
    _on_warning: Callable[[str], None]

    # ------------------------------------------------------------------ session and data
    _settings: Settings
    _n: int
    _length_m: float
    _data: TrackData | None
    _ref: TrackData | None
    _zones: list[float]
    _ref_zones: list[float]
    _status: list[SectorStatus]
    _bounds: list[float]
    _last: Sample | None
    _last_result: SectorResult | None
    _last_result_t: float
    _late_cut: str
    _late_cut_t: float

    # ------------------------------------------------------------------ sectors and passes
    _sector: int
    _pass: _Pass | None
    _last_closed: tuple[int, SectorRun] | None
    _lap_no: int
    _status_lap: int
    _lap_valid: bool | None
    _lap_saw_off: bool
    _lap_warned: bool
    _lap_runs: dict[tuple[int, int], _LapRun]
    _lap_notes: dict[tuple[int, int], SectorOutcome]
    _invalid_sectors: set[tuple[int, int]]
    _lines_lost: list[_LostPass]

    # ------------------------------------------------------------------ sector lines
    _learning_lines: bool
    _lines_laps: int
    _splits: dict[int, tuple[float, int, float]]
    _timeline: PositionTimeline

    # ------------------------------------------------------------------ cues and cut tracing
    _braking: bool
    _event: _BrakeEvent | None
    _fired_warn: set[float]
    _fired_here: set[float]
    _cut_active: bool
    _cut_gained: int
    _cut_deadline: int
    _prev_cut_active: bool
    _prev_cut_gained: int
    _prev_timing_invalid: bool

    # ------------------------------------------------------------------ passes
    def _pass_flag(self) -> DropReason | None: ...
    def _keep_onsets(self, run: _Pass | None) -> None: ...
    def _hold_lost(self, run: _Pass, sector: int, end: float) -> None: ...
    def _flag(self, reason: DropReason) -> None: ...
    def _unflag(self, reason: DropReason) -> None: ...
    def _prune_lap_runs(self) -> None: ...
    def _restart_pass(self, sector: int, t: float, pos: float) -> None: ...
    def _report(self, result: SectorResult) -> None: ...
    def _report_dropped(self, idx: int, outcome: SectorOutcome) -> None: ...
    def _already_out(self, lap: int, idx: int) -> bool: ...
    def _close_sector(self, t: float) -> None: ...
    def _lines_only(self, reasons: set[DropReason]) -> bool: ...

    # ------------------------------------------------------------------ sector lines
    def _start_line_learning(self) -> None: ...
    def _at_time(self, at: float) -> CarAt | None: ...
    def _car_now(self) -> CarAt | None: ...
    def _sector_of(self, pos: float) -> int: ...
    def _progress(self, pos: float) -> float: ...
    def _setup_bounds(self) -> None: ...
    def _lines_watch(self) -> None: ...
    def _settle_lines(self, message: str) -> bool: ...
    def report_split(self, index: int, at: float) -> None: ...
    def _audit_later_split(self, index: int, at: float) -> None: ...
    def _learn_split(self, index: int, at: float) -> None: ...
    def _audit_split(self, index: int, lap: int, at: float, car: CarAt) -> None: ...
    def _learn_lines(self, first: float, second: float) -> None: ...
    def _reanchor(self, run: _Pass, pos: float, t: float) -> None: ...
    def _retime_lost_sectors(self) -> None: ...
    def _store_late(self, entry: _LostPass, duration: float) -> bool: ...
    def _forget_early(self, onsets: list[float]) -> bool: ...
    def _crossing_time(self, lap: int, line: float) -> float | None: ...

    # ------------------------------------------------------------------ limits
    def _using_ref(self, i: int) -> bool: ...
    def _early_runs(self) -> list[list[SectorRun]]: ...
    def _rebuild_zones(self) -> None: ...
    def _check_track_limits(
        self, s: Sample, pos: float, prev: tuple[float, int] | None = None
    ) -> None: ...
    def _check_race_cut(self, s: Sample, pos: float) -> None: ...
    def _check_lap_flag(
        self, s: Sample, pos: float, prev: tuple[float, int] | None = None
    ) -> None: ...
    def _flag_attribution(
        self, pos: float, prev: tuple[float, int] | None
    ) -> tuple[float, int] | None: ...
    def report_infraction(self, reason: str, at: float) -> None: ...
    def _report_text(self, reason: str, where: float, lap: int, took_back: bool) -> str: ...
    def _laps_back(self, lap: int) -> str: ...
    def _lap_phrase(self, lap: int) -> str: ...
    def _drop_text(self, where: float, took_back: bool) -> str: ...
    def _attribute(self, reason: DropReason, where: float, lap: int) -> bool | None: ...
    def _drop_run(self, lap: int, idx: int) -> bool: ...
    def _trace_track_limits(self, s: Sample, pos: float) -> None: ...

    # ------------------------------------------------------------------ cues
    def _track_braking(self, s: Sample, pos: float) -> None: ...
    def _add_onset(self, pos: float) -> None: ...
    def _lead_m(self, speed_kmh: float) -> float: ...
    def _emit_cues(self, s: Sample, pos: float) -> None: ...

    # ------------------------------------------------------------------ engine
    def _save(self, data: TrackData) -> bool: ...
